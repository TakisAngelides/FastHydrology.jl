#!/usr/bin/env python3
"""Generate code_tour.ipynb from code_tour.jl, so the notebook never drifts from the script.

    python3 make_notebook.py            (writes code_tour.ipynb and notebook_extracted_check.jl)

Rules:
  * a banner  `# ====` / `# <title>` / `# ====`  followed by `#` prose lines becomes a markdown cell
    (title as a heading, prose with the leading `# ` stripped);
  * the code between banners becomes code cells, split before every `sub("...")` line;
  * notebook_extracted_check.jl is the concatenation of the code cells, in order: running it with
    `julia -t 4 notebook_extracted_check.jl` proves the notebook runs top to bottom.
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "code_tour.jl")
BANNER = re.compile(r"^# ={20,}\s*$")

lines = open(SRC).read().split("\n")
while lines and lines[-1] == "":
    lines.pop()


def prose(block):
    out = []
    for l in block:
        out.append(l[2:] if l.startswith("# ") else l[1:])
    text = "\n".join(out).strip("\n")
    # inline file paths and identifiers read better as code
    return text


cells = []          # (kind, text)
code = []


def flush_code():
    global code
    while code and code[0].strip() == "":
        code.pop(0)
    while code and code[-1].strip() == "":
        code.pop()
    if code:
        cells.append(("code", "\n".join(code)))
    code = []


i = 0
first_banner = True
while i < len(lines):
    l = lines[i]
    if BANNER.match(l) and i + 2 < len(lines) and BANNER.match(lines[i + 2]):
        flush_code()
        title = lines[i + 1].lstrip("#").strip()
        j = i + 3
        body = []
        while j < len(lines) and lines[j].startswith("#") and not BANNER.match(lines[j]):
            body.append(lines[j])
            j += 1
        if j < len(lines) and BANNER.match(lines[j]):  # closing banner of the header block
            j += 1
        if first_banner:
            md = "# FastHydrology Code Tour\n\n" + prose(body)
            md += ("\n\n*This notebook is generated from `code_tour.jl` by `make_notebook.py`; edit the script, "
                   "not the notebook. Run it with the **FastHydrology tour 1.13** kernel (Julia 1.13, project "
                   "`test/code_tour`), top to bottom; start Jupyter with `JULIA_NUM_THREADS=4` for the threaded "
                   "paths of PART 25.*")
            first_banner = False
        else:
            m = re.match(r"PART (\d+) -- (\S+): (.*)", title)
            if m:
                head = f"## Part {m.group(1)} — {m.group(3)} (`src/{m.group(2)}`)" if not m.group(2).startswith("ext/") \
                    else f"## Part {m.group(1)} — {m.group(3)} (`{m.group(2)}`)"
            elif re.match(r"PART (\d+) -- (\S+\.jl)$", title):
                n, f = re.match(r"PART (\d+) -- (\S+\.jl)$", title).groups()
                head = f"## Part {n} — `src/{f}`"
            elif re.match(r"PART (\d+) -- (.*)", title):
                n, t = re.match(r"PART (\d+) -- (.*)", title).groups()
                head = f"## Part {n} — {t[0].upper() + t[1:].lower()}"
            else:
                t, _, rest = title.partition(":")
                head = "## " + t.capitalize() + (":" + rest if rest else "")
            md = head + ("\n\n" + prose(body) if body else "")
        cells.append(("markdown", md))
        i = j
        continue
    if l.startswith("sub(") and any(c.strip() for c in code):
        flush_code()
    code.append(l)
    i += 1
flush_code()


def src(text):
    ls = text.split("\n")
    return [x + "\n" for x in ls[:-1]] + [ls[-1]]


nb = {
    "cells": [
        ({"cell_type": "markdown", "metadata": {}, "source": src(t)} if k == "markdown" else
         {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": src(t)})
        for k, t in cells
    ],
    "metadata": {
        "kernelspec": {"display_name": "FastHydrology tour 1.13", "language": "julia", "name": "fasthydrology-tour-1.13"},
        "language_info": {"file_extension": ".jl", "mimetype": "application/julia", "name": "julia", "version": "1.13.0"},
    },
    "nbformat": 4,
    "nbformat_minor": 5,
}
with open(os.path.join(HERE, "code_tour.ipynb"), "w") as f:
    json.dump(nb, f, indent=1, ensure_ascii=False)
    f.write("\n")

with open(os.path.join(HERE, "notebook_extracted_check.jl"), "w") as f:
    f.write("# Generated by make_notebook.py: the code cells of code_tour.ipynb, in order. Do not edit.\n")
    for k, t in cells:
        if k == "code":
            f.write(t + "\n\n")

ncode = sum(k == "code" for k, _ in cells)
print(f"code_tour.ipynb: {len(cells)} cells ({len(cells) - ncode} markdown, {ncode} code)")
